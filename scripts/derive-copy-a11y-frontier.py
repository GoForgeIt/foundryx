#!/usr/bin/env python3
"""An INDEPENDENT oracle for T13 A11 leg (a) — the copy / accessibility partition.

Written in a different language from the Swift check it pins, so the manifest is not a
golden file generated by the code it grades.  Emits `kind<TAB>path<TAB>literal`.

  a11y-identifier         the literal argument of `.accessibilityIdentifier("…")`
  customer-facing-string  the literal FIRST argument of `Text(`, `Button(`, `Label(`
                          and `.navigationTitle(` — the strings a person reads

Comments are stripped; string literals are kept, because the subject IS a string literal.
"""
import re
import sys
import pathlib

ROOT = pathlib.Path(sys.argv[1])
DIRS = ["App", "Widget", "Sources"]

CALLS = {
    "accessibilityIdentifier(": "a11y-identifier",
    "Text(": "customer-facing-string",
    "Button(": "customer-facing-string",
    "Label(": "customer-facing-string",
    "navigationTitle(": "customer-facing-string",
}


def strip_comments(text):
    out = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == '"':
            out.append(c)
            i += 1
            while i < n:
                c = text[i]
                out.append(c)
                if c == "\\":
                    if i + 1 < n:
                        out.append(text[i + 1])
                        i += 2
                        continue
                elif c == '"':
                    i += 1
                    break
                elif c == "\n":
                    i += 1
                    break
                i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            while i < n and text[i] != "\n":
                i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            i += 2
            while i + 1 < n and not (text[i] == "*" and text[i + 1] == "/"):
                if text[i] == "\n":
                    out.append("\n")
                i += 1
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def read_literal(text, j):
    """text[j] == '"'. Return (literal, index after the closing quote) or (None, j)."""
    n = len(text)
    lit = []
    k = j + 1
    while k < n:
        c = text[k]
        if c == "\\":
            if k + 1 < n:
                lit.append(c)
                lit.append(text[k + 1])
                k += 2
                continue
        if c == '"':
            return "".join(lit), k + 1
        if c == "\n":
            return None, j
        lit.append(c)
        k += 1
    return None, j


def rows_for(text, rel):
    rows = []
    for head, kind in CALLS.items():
        for m in re.finditer(re.escape(head), text):
            j = m.end()
            # Only a literal that opens the call IMMEDIATELY is the copy. A
            # `Text(viewModel.title)` carries no literal and is not on this frontier.
            if j < len(text) and text[j] == '"':
                literal, _ = read_literal(text, j)
                if literal is not None:
                    rows.append((kind, rel, literal))
    return rows


def main():
    rows = set()
    files = []
    for d in DIRS:
        base = ROOT / d
        if base.is_dir():
            files.extend(sorted(base.rglob("*.swift")))
    files.sort()
    for path in files:
        rel = str(path.relative_to(ROOT))
        rows.update(rows_for(strip_comments(path.read_text(encoding="utf-8")), rel))
    lines = sorted("\t".join(r) for r in rows)
    sys.stderr.write(f"ORACLE: {len(files)} file(s) walked, {len(lines)} row(s)\n")
    for line in lines:
        print(line)


main()
