#!/usr/bin/env python3
"""An INDEPENDENT oracle for T13 A5's persisted identifier frontier.

Written in a different language, from the criterion's prose, WITHOUT reading the Swift
derivation it is used to check.  The manifest this emits is the pin; if the Swift
derivation in `IdentifierFrontierTests` disagrees with it, one of the two is wrong and
the disagreement is the finding.  A golden file generated by the code it grades pins
that code's bugs.
"""
import re
import sys
import pathlib

ROOT = pathlib.Path(sys.argv[1])
SRC = ROOT / "Sources" / "FoundryXKit"
PERSISTED = ("json", "bin", "sqlite3", "plist")


def strip_comments(text):
    """Remove // and /* */ comments; keep string literals intact."""
    out = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c == '"':
            out.append(c)
            i += 1
            while i < n:
                c = text[i]
                out.append(c)
                if c == "\\":
                    if i + 1 < n:
                        out.append(text[i + 1])
                        i += 2
                        continue
                elif c == '"':
                    i += 1
                    break
                elif c == "\n":
                    i += 1
                    break
                i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            while i < n and text[i] != "\n":
                i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            i += 2
            while i + 1 < n and not (text[i] == "*" and text[i + 1] == "/"):
                if text[i] == "\n":
                    out.append("\n")
                i += 1
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def coding_keys(text, rel):
    rows = []
    for m in re.finditer(r"enum CodingKeys", text):
        j = m.end()
        header = ""
        while j < len(text) and text[j] != "{":
            header += text[j]
            j += 1
        if "String" not in header or j >= len(text):
            continue
        depth = 0
        body = []
        while j < len(text):
            ch = text[j]
            if ch == "{":
                depth += 1
                if depth == 1:
                    j += 1
                    continue
            if ch == "}":
                depth -= 1
                if depth == 0:
                    break
            body.append(ch)
            j += 1
        for line in "".join(body).split("\n"):
            line = line.strip()
            if not line.startswith("case "):
                continue
            for decl in line[len("case "):].split(","):
                decl = decl.strip()
                if decl:
                    rows.append(("coding-key", rel, decl))
    return rows


def on_disk(text, rel):
    rows = []
    i = 0
    n = len(text)
    while i < n:
        if text[i] != '"':
            i += 1
            continue
        j = i + 1
        lit = []
        closed = False
        while j < n:
            c = text[j]
            if c == "\\":
                if j + 1 < n:
                    lit.append(text[j + 1])
                    j += 2
                    continue
            if c == '"':
                closed = True
                break
            if c == "\n":
                break
            lit.append(c)
            j += 1
        literal = "".join(lit)
        # A literal that is ONLY an extension (".json") is not a persisted NAME.
        if closed and any(
            literal.endswith("." + e) and len(literal) > len(e) + 1 for e in PERSISTED
        ):
            rows.append(("on-disk-name", rel, literal))
        i = j + 1 if closed else i + 1
    return rows


def main():
    rows = set()
    files = sorted(SRC.rglob("*.swift"))
    for path in files:
        rel = str(path.relative_to(ROOT))
        text = strip_comments(path.read_text(encoding="utf-8"))
        rows.update(coding_keys(text, rel))
        rows.update(on_disk(text, rel))
    lines = sorted("\t".join(r) for r in rows)
    sys.stderr.write(f"ORACLE: {len(files)} file(s) walked, {len(lines)} frontier identifier(s)\n")
    for line in lines:
        print(line)


main()
