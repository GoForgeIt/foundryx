import XCTest
import Foundation

/// T13 / A11 — THE COPY / ACCESSIBILITY PARTITION IS NULL-CHANGED, AND `G-BRAND` IS NOT
/// THEREBY DISCHARGED.
///
/// ## One criterion, one conjunction, one disposition
///
/// A11's spec forbids substituting one conjunct for the other in as many words — *"This
/// spec has no authority to substitute (a) for (b); only Nick can grant that exception"*,
/// and *"omitting the probe fails A11"*. So this file grades BOTH legs, and the second one
/// is the one that makes the criterion falsifiable about itself:
///
///   (a) every customer-facing string and accessibility identifier byte-unchanged, WITH
///       THE COMPARED COUNT REPORTED — `testTheCopyPartitionIsNullChanged` and
///       `testTheAccessibilityPartitionIsNullChanged`;
///   (b) the `T-BRANDGATE` runnability probe and a TRUTHFUL `G-BRAND` status record —
///       `testTheGBrandRecordCarriesTheProbeItClaims`. Recording `G-BRAND` satisfied on
///       leg (a) alone, with no probe result in the evidence pack, is A11's own stated
///       falsifier, and it goes red here.
///
/// ## The oracle is outside the code it grades
///
/// `evidence/t13/copy-a11y-frontier.tsv` was emitted by
/// `scripts/derive-copy-a11y-frontier.py`, an independent implementation in another
/// language, and the two agree row for row. A golden file generated by the code it grades
/// pins that code's bugs.
///
/// ## What is on this frontier, and — measured — what is not
///
/// KIND `a11y-identifier`        the literal argument of `.accessibilityIdentifier("…")`.
///                               `door-url-field` is one of them.
/// KIND `customer-facing-string` the literal FIRST argument of `Text(`, `Button(`,
///                               `Label(` and `.navigationTitle(`.
///
/// NOT ON IT, stated rather than implied away: interpolated and computed copy
/// (`Text(viewModel.title)` carries no literal), `LocalizedStringKey` tables, alert and
/// confirmation-dialog titles, and every string under `Tests/` and `UITests/`. A frontier
/// that quietly meant "whatever I happened to parse" would be a completeness claim nobody
/// measured.
final class CopyAndAccessibilityFrontierTests: XCTestCase {

    private static let searchRoots = ["App", "Widget", "Sources"]
    private static let manifestPath = "evidence/t13/copy-a11y-frontier.tsv"
    private static let gBrandRecordPath = "evidence/t13/g-brand-status.md"

    /// Head-of-call to kind. Only a literal that opens the call IMMEDIATELY is copy.
    private static let calls: [(head: String, kind: String)] = [
        ("accessibilityIdentifier(", "a11y-identifier"),
        ("Text(", "customer-facing-string"),
        ("Button(", "customer-facing-string"),
        ("Label(", "customer-facing-string"),
        ("navigationTitle(", "customer-facing-string"),
    ]

    private struct Row: Hashable, Comparable {
        let kind: String
        let path: String
        let literal: String
        var line: String { "\(kind)\t\(path)\t\(literal)" }
        static func < (a: Row, b: Row) -> Bool { a.line < b.line }
    }

    private static func repoRoot() -> URL {
        var url = URL(fileURLWithPath: #filePath)
        for _ in 0..<3 { url.deleteLastPathComponent() }
        return url
    }

    private static func relativePath(_ url: URL) -> String {
        let root = repoRoot().path.hasSuffix("/") ? repoRoot().path : repoRoot().path + "/"
        return url.path.hasPrefix(root) ? String(url.path.dropFirst(root.count)) : url.path
    }

    private static func swiftFiles() -> [URL] {
        var files: [URL] = []
        for directory in searchRoots {
            let base = repoRoot().appendingPathComponent(directory, isDirectory: true)
            var isDirectory: ObjCBool = false
            guard FileManager.default.fileExists(atPath: base.path, isDirectory: &isDirectory),
                  isDirectory.boolValue,
                  let walk = FileManager.default.enumerator(
                    at: base, includingPropertiesForKeys: [.isRegularFileKey]) else { continue }
            for case let url as URL in walk where url.pathExtension == "swift" {
                files.append(url)
            }
        }
        return files.sorted { $0.path < $1.path }
    }

    /// `//` and `/* … */` removed; string literals kept intact.
    private static func stripComments(_ source: String) -> String {
        var out = ""
        var inString = false, inLineComment = false, inBlockComment = false, escaped = false
        var previous: Character? = nil
        for character in source {
            if inLineComment {
                if character == "\n" { inLineComment = false; out.append(character) }
                previous = character
                continue
            }
            if inBlockComment {
                if previous == "*" && character == "/" { inBlockComment = false; previous = nil; continue }
                if character == "\n" { out.append(character) }
                previous = character
                continue
            }
            if inString {
                out.append(character)
                if escaped { escaped = false }
                else if character == "\\" { escaped = true }
                else if character == "\"" { inString = false }
                previous = character
                continue
            }
            if previous == "/" && character == "/" { out.removeLast(); inLineComment = true; previous = nil; continue }
            if previous == "/" && character == "*" { out.removeLast(); inBlockComment = true; previous = nil; continue }
            if character == "\"" { inString = true }
            out.append(character)
            previous = character
        }
        return out
    }

    private static func literal(_ text: [Character], at index: Int) -> String? {
        guard index < text.count, text[index] == "\"" else { return nil }
        var literal = ""
        var cursor = index + 1
        while cursor < text.count {
            let character = text[cursor]
            if character == "\\" {
                if cursor + 1 < text.count {
                    literal.append(character); literal.append(text[cursor + 1]); cursor += 2; continue
                }
            }
            if character == "\"" { return literal }
            if character == "\n" { return nil }
            literal.append(character)
            cursor += 1
        }
        return nil
    }

    private static func derived() -> [Row] {
        var rows: Set<Row> = []
        for file in swiftFiles() {
            guard let raw = try? String(contentsOf: file, encoding: .utf8) else { continue }
            let text = Array(stripComments(raw))
            let path = relativePath(file)
            for call in calls {
                let head = Array(call.head)
                var index = 0
                while index + head.count <= text.count {
                    guard Array(text[index..<(index + head.count)]) == head else { index += 1; continue }
                    if let value = literal(text, at: index + head.count) {
                        rows.insert(Row(kind: call.kind, path: path, literal: value))
                    }
                    index += head.count
                }
            }
        }
        return rows.sorted()
    }

    private static func manifest() -> [Row] {
        let url = repoRoot().appendingPathComponent(manifestPath)
        guard let text = try? String(contentsOf: url, encoding: .utf8) else {
            XCTFail("REFUSED: the pinned copy/a11y manifest \(manifestPath) does not exist. "
                  + "A comparison against an absent oracle is not a pass.")
            return []
        }
        var rows: [Row] = []
        for rawLine in text.split(separator: "\n") {
            let line = String(rawLine)
            if line.hasPrefix("#") || line.trimmingCharacters(in: .whitespaces).isEmpty { continue }
            let fields = line.components(separatedBy: "\t")
            guard fields.count == 3 else {
                XCTFail("REFUSED: malformed manifest row: \(line)")
                continue
            }
            rows.append(Row(kind: fields[0], path: fields[1], literal: fields[2]))
        }
        return rows.sorted()
    }

    private func assertPartitionUnchanged(kind: String) {
        let derived = Set(Self.derived().filter { $0.kind == kind })
        let pinned = Set(Self.manifest().filter { $0.kind == kind })

        // THE COMPARED COUNT, REPORTED. A11 asks for it by name, and it is the only thing
        // that distinguishes "nothing changed" from "nothing was compared".
        print("COPY/A11Y PARTITION `\(kind)`: \(derived.count) compared, \(pinned.count) pinned.")
        XCTAssertGreaterThan(
            derived.count, 0,
            "VACUOUS: ZERO `\(kind)` rows were compared. A partition that compares nothing "
          + "is null-changed for free, and reporting it as unchanged would be a green over "
          + "an empty population.")

        let changed = derived.subtracting(pinned).sorted()
        let missing = pinned.subtracting(derived).sorted()
        if !changed.isEmpty || !missing.isEmpty {
            var report = "COPY/A11Y PARTITION `\(kind)` IS NOT NULL-CHANGED: "
                       + "\(derived.count) compared, \(pinned.count) pinned, "
                       + "\(changed.count) changed-or-added, \(missing.count) missing.\n"
            for row in changed { report += "  CHANGED-OR-ADDED  \(row.line)\n" }
            for row in missing { report += "  MISSING  \(row.line)\n" }
            XCTFail(report)
        }
    }

    func testTheCopyPartitionIsNullChanged() {
        assertPartitionUnchanged(kind: "customer-facing-string")
    }

    func testTheAccessibilityPartitionIsNullChanged() {
        assertPartitionUnchanged(kind: "a11y-identifier")
    }

    /// LEG (b). A11's own falsifier, verbatim from its disposition: *record `G-BRAND`
    /// satisfied on leg (a) alone with no probe result in the evidence pack -> red on the
    /// missing probe*. This is that red.
    ///
    /// The rule is deliberately asymmetric, because the two verdicts carry different
    /// burdens. `DISCHARGED` may only be recorded beside a probe that RAN the gate and
    /// compared its results; `OPEN` may only be recorded beside a probe that names what
    /// BLOCKED it. A status with no probe section at all is refused either way — that is
    /// the state where leg (a)'s green would have been silently promoted into A11's.
    func testTheGBrandRecordCarriesTheProbeItClaims() throws {
        let url = Self.repoRoot().appendingPathComponent(Self.gBrandRecordPath)
        guard let text = try? String(contentsOf: url, encoding: .utf8) else {
            XCTFail("REFUSED: \(Self.gBrandRecordPath) does not exist. A11 puts the "
                  + "`T-BRANDGATE` probe at track start and makes omitting it a failure of "
                  + "A11; with no record there is nothing that could be truthful.")
            return
        }

        let statusLine = text.split(separator: "\n")
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .first { $0.hasPrefix("G-BRAND:") }
        guard let status = statusLine else {
            XCTFail("REFUSED: \(Self.gBrandRecordPath) records no `G-BRAND:` status line. "
                  + "The criterion requires the status to be recorded, truthfully.")
            return
        }

        let hasProbeSection = text.contains("## PROBE RESULT")
        XCTAssertTrue(
            hasProbeSection,
            "G-BRAND IS RECORDED WITH NO PROBE RESULT — `\(status)` stands beside no "
          + "`## PROBE RESULT` section in \(Self.gBrandRecordPath). This is A11's own stated "
          + "falsifier: leg (a) passing is not leg (b) passing, and a status recorded without "
          + "the probe that would justify it is leg (a)'s green wearing A11's name.")
        guard hasProbeSection else { return }

        let probe = String(text[text.range(of: "## PROBE RESULT")!.lowerBound...])
        if status.contains("DISCHARGED") {
            XCTAssertTrue(
                probe.contains("predicates resolved:") && probe.contains("at both commits"),
                "G-BRAND: DISCHARGED requires a probe that RAN the gate at both commits with "
              + "its predicate count reported. The probe section carries neither.")
        } else {
            XCTAssertTrue(
                probe.contains("BLOCKED BY:"),
                "G-BRAND is not DISCHARGED, so the probe section must name what BLOCKED it — "
              + "`BLOCKED BY:` is absent. `OPEN` with no named blocker is an unfalsifiable "
              + "status: nothing about it could ever be wrong.")
        }
        print("G-BRAND RECORD: \(status) — probe section present, "
            + "\(probe.split(separator: "\n").count) line(s).")
    }
}
